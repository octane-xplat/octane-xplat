#!/usr/bin/env node
// pnpm is retained for pack/publish and consumer qualification. Its workspace
// file is generated packaging metadata; Bun's package.json owns all versions.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { stringify } from 'yaml'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))
const workspace = pkg.workspaces
const config = {
	pmOnFail: 'ignore',
	packages: Array.isArray(workspace) ? workspace : workspace.packages,
	catalog: pkg.catalog ?? workspace.catalog,
	catalogs: pkg.catalogs ?? workspace.catalogs,
}

const after =
	'# Generated by bun run sync:workspace from package.json.\n# For pnpm pack/publish only; install the repository with Bun.\n' +
	stringify(config)

const file = join(root, 'pnpm-workspace.yaml')
if (readFileSync(file, 'utf8') !== after) {
	if (process.argv.includes('--check')) {
		console.error('Packaging workspace metadata is stale; run bun run sync:workspace.')
		process.exitCode = 1
	} else {
		writeFileSync(file, after)
	}
}
