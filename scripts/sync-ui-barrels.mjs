#!/usr/bin/env node
// Keep the web barrels' explicit file paths aligned with the shared API list.
// Declaration emit requires .tsrx specifiers, while the web build needs .web
// leaves wherever they exist. Each shared entrypoint gets a generated .web
// twin so dev consumers resolve web leaves without suffix negotiation.
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const sourceDir = join(root, 'packages/ui/src')
const check = process.argv.includes('--check')

// [source, generated web twin] — both live under src/, so './x' and '../x'
// specifiers resolve against the source file's own directory.
const barrels = [
	'index.shared.ts',
	'routing/index.ts',
	'data/index.ts',
	'markdown/index.ts',
	'chat/index.ts',
]

const webSpecifier = (dir, specifier) => {
	const extension = specifier.endsWith('.tsrx') ? '.tsrx' : ''
	const base = extension ? specifier.slice(0, -extension.length) : specifier
	const candidate = `${base}.web${extension}`
	if (existsSync(join(dir, `${candidate}${extension ? '' : '.ts'}`))) {
		return candidate
	}

	if (extension && /@jsxImportSource/.test(readFileSync(join(dir, specifier), 'utf8'))) {
		throw new Error(`shared UI export ${specifier} has no ${candidate} leaf`)
	}

	return specifier
}

let stale = 0
for (const barrel of barrels) {
	const sourcePath = join(sourceDir, barrel)
	const dir = dirname(sourcePath)
	const source = readFileSync(sourcePath, 'utf8')
	const webName = barrel === 'index.shared.ts' ? 'index.shared.web.ts' : 'index.web.ts'
	const outFile = join(dir, webName)
	const generated =
		`// Generated by scripts/sync-ui-barrels.mjs from ${barrel}. Do not edit.\n` +
		source.replace(
			/(from\s+['"])(\.\.?\/[^'"]+)(['"])/g,
			(_, before, specifier, after) => `${before}${webSpecifier(dir, specifier)}${after}`,
		)

	if (existsSync(outFile) && readFileSync(outFile, 'utf8') === generated) {
		console.log(`UI web barrel ${barrel} in sync`)
	} else if (check) {
		console.error(
			`packages/ui/src/${join(dirname(barrel), webName)} is stale; run pnpm sync:ui-barrels`,
		)

		stale++
	} else {
		writeFileSync(outFile, generated)
		console.log(`updated ${outFile.replace(`${root}/`, '')}`)
	}
}

if (stale) {
	process.exitCode = 1
}
