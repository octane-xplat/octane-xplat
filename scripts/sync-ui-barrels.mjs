#!/usr/bin/env node
// Keep the web barrel's explicit file paths aligned with the shared API list.
// Declaration emit requires .tsrx specifiers, while the web build needs .web
// leaves wherever they exist.
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const sourceDir = join(root, 'packages/ui/src')
const source = readFileSync(join(sourceDir, 'index.shared.ts'), 'utf8')
const output = join(sourceDir, 'index.shared.web.ts')
const check = process.argv.includes('--check')

const webSpecifier = (specifier) => {
	const extension = specifier.endsWith('.tsrx') ? '.tsrx' : ''
	const base = extension ? specifier.slice(0, -extension.length) : specifier
	const candidate = `${base}.web${extension}`
	if (existsSync(join(sourceDir, `${candidate}${extension ? '' : '.ts'}`))) {
		return candidate
	}

	if (extension) {
		throw new Error(`shared UI export ${specifier} has no ${candidate} leaf`)
	}

	return specifier
}

const generated =
	'// Generated by scripts/sync-ui-barrels.mjs from index.shared.ts. Do not edit.\n' +
	source.replace(
		/(from\s+['"])(\.\/[^'"]+)(['"])/g,
		(_, before, specifier, after) => `${before}${webSpecifier(specifier)}${after}`,
	)

if (existsSync(output) && readFileSync(output, 'utf8') === generated) {
	console.log('UI web barrel in sync')
} else if (check) {
	console.error('packages/ui/src/index.shared.web.ts is stale; run pnpm sync:ui-barrels')
	process.exitCode = 1
} else {
	writeFileSync(output, generated)
	console.log('updated packages/ui/src/index.shared.web.ts')
}
