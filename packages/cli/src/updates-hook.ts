import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { join } from 'node:path'

// Shared generated hook; registration does not execute the optional runtime.
export const updatesHook = `// Generated by xplat updates init. Commit this hook with your app.\nmodule.exports = function (hookArgs) {\n\tconst projectDir = hookArgs.projectData.projectDir\n\tconst platform = hookArgs.platformData?.platformName ?? hookArgs.prepareData?.platform\n\treturn require('@octane-xplat/updates/prepare')({ projectDir, platform, projectName: hookArgs.projectData.projectName, platformsDir: hookArgs.projectData.platformsDir, nativeConfig: hookArgs.projectData.nsConfig, release: hookArgs.prepareData?.release ?? hookArgs.buildData?.release ?? false })\n}\n`

export async function initializeUpdates(root) {
	// Resolve the optional runtime from the app, never from the CLI's own dependencies.
	createRequire(join(root, 'package.json')).resolve('@octane-xplat/updates/prepare')
	createRequire(join(root, 'package.json')).resolve('@octane-xplat/fingerprint')
	const folder = join(root, 'hooks/after-prepare')
	const destination = join(folder, 'xplat-updates.cjs')

	let existing
	try {
		existing = await readFile(destination, 'utf8')
	} catch (error) {
		if (error.code !== 'ENOENT') {
			throw error
		}
	}

	if (existing && existing !== updatesHook) {
		throw new Error('Existing OTA hook differs; reconcile it before running updates init')
	}

	await mkdir(folder, { recursive: true })
	await writeFile(destination, updatesHook)
	const ignoreFile = join(root, '.gitignore')
	let ignored = ''
	try {
		ignored = await readFile(ignoreFile, 'utf8')
	} catch (error) {
		if (error.code !== 'ENOENT') {
			throw error
		}
	}
	if (!ignored.split(/\r?\n/).some((line) => ['.xplat/', '/.xplat/'].includes(line.trim()))) {
		await writeFile(
			ignoreFile,
			ignored + (ignored && !ignored.endsWith('\n') ? '\n' : '') + '.xplat/\n',
		)
	}
	return destination
}
