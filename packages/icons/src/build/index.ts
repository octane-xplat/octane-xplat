// Registry codegen: scan app sources for `icons:<prefix>/<name>` imports and
// emit one `addIcons` module so every imported icon also resolves by name.
// Default output re-imports the `icons:` specifiers (Vite targets, zero
// duplication); `--inline` writes the icon data directly so the generated
// file works on bundlers without the plugin (iOS/Android).
import fsp from 'node:fs/promises'
import fs from 'node:fs'
import { extname, isAbsolute, join } from 'node:path'

import type { IconifyIcon } from '@iconify/types'

import { iconSpecifierParts, readIconData, resolveCollectionJson } from './resolve'

export { iconSpecifierParts, readIconData, resolveCollectionJson } from './resolve'

const sourceExtensions = new Set(['.ts', '.tsx', '.tsrx', '.mts', '.cts', '.mjs', '.cjs', '.jsx'])
const specifierPattern = /['"`](icons:[a-z0-9]+(?:-[a-z0-9]+)*\/[a-z0-9]+(?:-[a-z0-9]+)*)['"`]/g
const skippedDirs = new Set(['node_modules', 'dist', 'out', 'build'])

/** Options for the icon-registry emission. */
export interface IconRegistryOptions {
	/** App root — scanned for `icons:` specifiers and anchors @iconify-json resolution. */
	root: string
	/** Emitted module path, relative to root. Default `src/icons.gen.ts`. */
	out?: string
	/** Extra directories or files to scan, relative to root. Default `['src']`. */
	include?: string[]
	/** Write IconifyIcon data inline instead of `icons:` imports — for bundlers without the plugin. */
	inline?: boolean
}

/** Artifacts of the emission. */
export interface IconRegistryResult {
	/** Absolute path of the emitted module. */
	file: string
	/** `prefix:name` names registered, sorted. */
	icons: string[]
	/** True when the existing file already matched. */
	unchanged: boolean
}

async function* walk(dir: string, outFile: string): AsyncGenerator<string> {
	let entries
	try {
		entries = await fsp.readdir(dir, { withFileTypes: true })
	} catch {
		return
	}

	for (const entry of entries) {
		const file = join(dir, entry.name)
		if (entry.isDirectory()) {
			if (!skippedDirs.has(entry.name) && !entry.name.startsWith('.')) {
				yield* walk(file, outFile)
			}
		} else if (sourceExtensions.has(extname(entry.name)) && file !== outFile) {
			yield file
		}
	}
}

async function scanSpecifiers(root: string, include: string[], outFile: string): Promise<Set<string>> {
	const specifiers = new Set<string>()
	for (const entry of include) {
		const target = join(root, entry)
		const stat = await fsp.stat(target).catch(() => undefined)
		if (stat?.isDirectory()) {
			for await (const file of walk(target, outFile)) {
				for (const match of (await fsp.readFile(file, 'utf8')).matchAll(specifierPattern)) {
					specifiers.add(match[1])
				}
			}
		} else if (stat && sourceExtensions.has(extname(target)) && target !== outFile) {
			for (const match of (await fsp.readFile(target, 'utf8')).matchAll(specifierPattern)) {
				specifiers.add(match[1])
			}
		}
	}

	return specifiers
}

/**
 * Emit a module that registers every `icons:<prefix>/<name>` specifier found
 * in the app's sources through `addIcons`, so the same tree-shaken data also
 * resolves by `name=`. Every specifier is resolved against its
 * `@iconify-json` collection at emit time — a missing collection or icon
 * fails the emit. Import the emitted file once at app startup.
 */
export async function emitIconRegistry(options: IconRegistryOptions): Promise<IconRegistryResult> {
	const root = options.root
	const outFile = isAbsolute(options.out ?? '')
		? (options.out as string)
		: join(root, options.out ?? 'src/icons.gen.ts')
	const specifiers = [...(await scanSpecifiers(root, options.include ?? ['src'], outFile))].sort()

	const anchor = join(root, 'package.json')
	const icons = new Map<string, IconifyIcon>()
	for (const specifier of specifiers) {
		const [prefix, name] = iconSpecifierParts(specifier) as [string, string]
		const jsonPath = resolveCollectionJson(prefix, anchor)
		if (!jsonPath) {
			throw new Error(`Cannot resolve @iconify-json/${prefix} for "${specifier}" — install the collection package.`)
		}

		const icon = readIconData(jsonPath, name)
		if (!icon) {
			throw new Error(`Icon "${name}" not found in @iconify-json/${prefix} — check the name against its icons.json.`)
		}

		icons.set(specifier, icon)
	}

	const inline = options.inline ?? false
	const lines: string[] = [
		'// Generated by @octane-xplat/icons — regenerate with `xplat-icons register`. Do not edit.',
		`import { addIcons } from '@octane-xplat/icons'`,
	]
	if (!inline) {
		for (const [index, specifier] of specifiers.entries()) {
			lines.push(`import icon${index} from '${specifier}'`)
		}
	}

	lines.push('', 'addIcons({')
	for (const [index, specifier] of specifiers.entries()) {
		const name = specifier.slice('icons:'.length).replace('/', ':')
		lines.push(`\t'${name}': ${inline ? JSON.stringify(icons.get(specifier)) : `icon${index}`},`)
	}

	lines.push('})', '')
	const source = lines.join('\n')

	const unchanged = fs.existsSync(outFile) && fs.readFileSync(outFile, 'utf8') === source
	if (!unchanged) {
		await fsp.mkdir(join(outFile, '..'), { recursive: true })
		const tmp = `${outFile}.${process.pid}.tmp`
		fs.writeFileSync(tmp, source)
		fs.renameSync(tmp, outFile)
	}

	return {
		file: outFile,
		icons: specifiers.map((s) => s.slice('icons:'.length).replace('/', ':')),
		unchanged,
	}
}
