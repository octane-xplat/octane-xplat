import { readFile, writeFile } from 'node:fs/promises'
import postcss from 'postcss'
import { defaultThemeTokens } from '../../ui/src/theme/astryx-default-tokens.ts'

// Register names only. UI's runtime stylesheet owns values and scope/mode
// changes; reference+inline prevents emitting self-referencing declarations.
const names = new Set(Object.keys(defaultThemeTokens))
const chrome = postcss.parse(
  await readFile(new URL('../../ui/src/theme/chrome.css', import.meta.url), 'utf8'),
)

chrome.walkDecls((declaration) => {
  names.add(declaration.prop)
})

const tokens = [...names].filter((name) => /^--(?:color|radius)-/.test(name)).sort()
const css = `/* Generated by bun run sync:ui-theme in packages/tailwind.
   Names come from UI's default tokens and chrome; values remain runtime-owned. */
@theme reference inline {
${tokens.map((name) => `  ${name}: var(${name});`).join('\n')}
}
`

await writeFile(new URL('../src/ui-theme.css', import.meta.url), css)
