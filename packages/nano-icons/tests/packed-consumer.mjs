import assert from 'node:assert/strict'
import { spawnSync } from 'node:child_process'
import {
	cpSync,
	mkdirSync,
	mkdtempSync,
	readdirSync,
	readFileSync,
	rmSync,
	symlinkSync,
	writeFileSync,
} from 'node:fs'

import { tmpdir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const repoRoot = resolve(packageRoot, '../..')
const temporary = mkdtempSync(join(tmpdir(), 'octane-nano-icons-consumer-'))

function run(command, args, cwd) {
	const result = spawnSync(command, args, { cwd, encoding: 'utf8', maxBuffer: 16 * 1024 * 1024 })
	if (result.stdout) {
		process.stdout.write(result.stdout)
	}

	if (result.stderr) {
		process.stderr.write(result.stderr)
	}

	if (result.error) {
		throw result.error
	}

	assert.equal(result.status, 0, `${command} ${args.join(' ')} failed`)
}

try {
	const pack = join(temporary, 'pack')
	const extracted = join(temporary, 'extracted')
	mkdirSync(pack)
	mkdirSync(extracted)
	run('pnpm', ['pack', '--pack-destination', pack], packageRoot)
	const tarball = readdirSync(pack).find((name) => name.endsWith('.tgz'))
	assert.ok(tarball)
	run('tar', ['-xzf', join(pack, tarball), '-C', extracted], temporary)
	const packed = join(extracted, 'package')
	const manifest = JSON.parse(readFileSync(join(packed, 'package.json'), 'utf8'))
	for (const dep of ['@octane-xplat/icons', '@octane-xplat/ui']) {
		assert.equal(manifest.dependencies[dep].startsWith('workspace:'), false)
	}

	assert.ok(manifest.exports['.'].web.default.startsWith('./dist/'))
	assert.ok(manifest.exports['.'].native.default.startsWith('./dist/'))
	assert.ok(manifest.exports['.'].macos.default.startsWith('./dist/'))
	const macosComponent = readFileSync(join(packed, 'dist/macos/NanoIcon.macos.js'), 'utf8')
	assert.match(macosComponent, /defineUniversalComponent\("macos"/)
	assert.doesNotMatch(macosComponent, /from ["'](?:octane|@xplat\/macos\/renderer)["']/)
	for (const target of ['web', 'native', 'macos']) {
		for (const mode of ['bundler', 'nodenext']) {
			const consumer = join(temporary, `${target}-${mode}`)
			const modules = join(consumer, 'node_modules')
			mkdirSync(join(modules, '@octane-xplat'), { recursive: true })
			cpSync(packed, join(modules, '@octane-xplat/nano-icons'), { recursive: true })
			for (const dependency of [
				'octane',
				'@iconify/types',
				'@iconify/utils',
				...(target === 'native' ? ['@nativescript-community/octane'] : []),
				...(target === 'macos' ? ['@octane-xplat/macos-renderer'] : []),
			]) {
				const destination = join(modules, dependency)
				mkdirSync(dirname(destination), { recursive: true })
				symlinkSync(join(packageRoot, 'node_modules', dependency), destination, 'dir')
			}

			// Workspace packages are linked directly: their exports carry the same
			// conditions, with types generated by the repo's postinstall typegen.
			for (const workspacePackage of ['icons', 'ui']) {
				symlinkSync(
					join(repoRoot, 'packages', workspacePackage),
					join(modules, '@octane-xplat', workspacePackage),
					'dir',
				)
			}

			writeFileSync(join(consumer, 'package.json'), '{"type":"module"}')
			writeFileSync(
				join(consumer, 'consumer.tsx'),
				`
import { NanoIcon, prepareNanoIcon, materializeNanoIcon, type NanoIconProps, type NanoIconOptions, type PreparedNanoIcon, type IconSvg, type IconifyIcon } from '@octane-xplat/nano-icons'
import { addCollection, resolveIcon } from '@octane-xplat/icons'
const collection = { prefix: 'app', icons: { arrow: { body: '<path d="M0 0h16"/>' } } }
addCollection(collection)
const data: IconifyIcon | undefined = resolveIcon('app:arrow')
const options: NanoIconOptions = { size: 20, rotate: 1, hFlip: true }
const prepared: PreparedNanoIcon | undefined = data ? prepareNanoIcon(data, options) : undefined
const svg: IconSvg | undefined = prepared ? materializeNanoIcon(prepared, { color: 'red' }) : undefined
void svg
const props: NanoIconProps = { name: 'app:arrow', size: 20, label: 'Next', hFlip: true }
const element = <NanoIcon {...props} />
// @ts-expect-error name is required
const missing = <NanoIcon size={20} />
// @ts-expect-error dimensions are numbers on every target
const invalid = <NanoIcon name="app:arrow" size="1em" />
// @ts-expect-error tint belongs to materialization, not preparation
const tinted = prepareNanoIcon(data, { ...options, color: 'red' })
void element; void missing; void invalid; void tinted
`,
			)

			writeFileSync(
				join(consumer, 'tsconfig.json'),
				JSON.stringify({
					compilerOptions: {
						strict: true,
						noEmit: true,
						skipLibCheck: true,
						target: 'esnext',
						types: [],
						module: mode === 'bundler' ? 'esnext' : 'nodenext',
						moduleResolution: mode,
						jsx: 'react-jsx',
						jsxImportSource:
							target === 'native'
								? '@nativescript-community/octane'
								: target === 'macos'
									? '@octane-xplat/macos-renderer'
									: 'octane',
						customConditions: [target],
						moduleSuffixes:
							target === 'web'
								? ['.web', '']
								: target === 'macos'
									? ['.macos', '']
									: ['.mobile', ''],
					},
					files: ['consumer.tsx'],
				}),
			)

			run(
				process.execPath,
				[join(packageRoot, 'node_modules/typescript/bin/tsc'), '-p', 'tsconfig.json'],
				consumer,
			)
		}
	}

	console.log('nano-icons packed consumer: web/native/macos declarations pass Bundler and NodeNext')
} finally {
	rmSync(temporary, { recursive: true, force: true })
}
