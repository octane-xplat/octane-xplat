// Generated-runtime-module emission: writes a typed TS module next to the
// built font assets so apps get a `createNanoIconSet`-bound component with
// literal icon names, plus the platform font source wiring.
import path from 'node:path'

import type { NanoGlyphMap } from './core/types'
import { ensureDir, writeFileAtomic } from './core/config'
import { manifestBaseName } from './core/naming'

/** Escape a string for embedding inside a single-quoted TS literal. */
function tsString(value: string): string {
	return `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`
}

/**
 * Emit `<fontFamily>.ts` beside the font assets. The module exports the
 * glyphmap, a bound `NanoIconSet`, a `NanoIcon` alias for `set.Icon`, and a
 * union type of icon names. `url` is a lazy getter so non-web runtimes never
 * evaluate `import.meta.url` resolution.
 */
export function emitNanoIconSetModule(options: {
	outputDir: string
	fontFamily: string
	family: string
	glyphMap: NanoGlyphMap
	web: boolean
}): string {
	const base = manifestBaseName(options.fontFamily)
	const fontFile = `${options.family}.ttf`
	const names = Object.keys(options.glyphMap.i)

	const urlLine = options.web
		? `get url() {\n\t\treturn new URL('./${options.family}.woff2', import.meta.url).href;\n\t},`
		: `get url() {\n\t\treturn new URL('./${fontFile}', import.meta.url).href;\n\t},`

	const source = `// Generated by @octane-xplat/nano-icons. Regenerate with the nano-icons build — do not edit.
import { createNanoIconSet } from '@octane-xplat/nano-icons';
import type { NanoIconSet } from '@octane-xplat/nano-icons';

export const glyphMap = ${JSON.stringify(options.glyphMap)} as const;

/** iOS/Android: copy ${tsString(fontFile)} into the app's fonts directory (see @octane-xplat/nano-icons docs). */
export const ${base}Icons: NanoIconSet<${base}IconName> = createNanoIconSet(glyphMap, {
	font: {
		// NativeScript resolves app fonts by file name; keep it equal to the family.
		fileName: ${tsString(fontFile)},
		// Web font source; evaluated lazily so native bundles never touch import.meta.url.
		${urlLine}
	},
});

export const NanoIcon = ${base}Icons.Icon;

export type ${base}IconName =
${names.length ? names.map((n) => `\t| ${tsString(n)}`).join('\n') : '\t| never'};
`

	ensureDir(options.outputDir)
	const modulePath = path.join(options.outputDir, `${options.fontFamily}.ts`)
	writeFileAtomic(modulePath, source)
	return modulePath
}
