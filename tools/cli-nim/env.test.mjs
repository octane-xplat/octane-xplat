test('relative roots resolve against cwd and a failed expansion preserves the previous program', () => {
 const dir = fixture(web({ include: ['src/*.ts'] }))
 const [first] = compare([{ operation: 'expand', dir: relative(process.cwd(), dir) }])
 assert.equal(first.ok, true)
 const configPath = first.value.programs[0].configPath
 const written = readFileSync(configPath, 'utf8')
 writeFileSync(join(dir, 'tsconfig.envs.json'), JSON.stringify(web({ files: ['missing.ts'] })))
 const [failed] = compare([{ operation: 'expand', dir }])
 assert.equal(failed.ok, false)
 assert.equal(readFileSync(configPath, 'utf8'), written)
})

