test('JSONC leaves quoted data intact and rejects malformed input', () => {
 const texts = [
  undefined, '{}', 'null', '[]', '{"environments":{}}', '{"environments":[]}',
  '{ /* comment */ "environments":{"web":{"files":["src/index.ts",],},}, // tail\n}',
  JSON.stringify({ ...web({ files: ['src/index.ts'] }), compilerOptions: { paths: { ',}': [',]', '/* keep */'] } } }),
  '{"environments":{"web":{"files":[,]}}}', '{"environments":{"web":{,}}}',
  '{"environments":{"web":{}}} /* unterminated', '{"environments":{"web":{}}} extra',
 ]
 for (const text of texts) {
  const dir = fixture(undefined)
  if (text !== undefined) writeFileSync(join(dir, 'tsconfig.envs.json'), text)
  const malformed = text?.includes('[,]') || text?.includes('{,}') || text?.endsWith('unterminated') || text?.endsWith('extra')
  compare([{ operation: 'load', dir }], { exactErrors: !malformed })
 }
})

